"""Refresh the checked-in RAG corpus from the four supplied resume PDFs.
Run with a Python environment containing pypdf. No source PDF is uploaded.
"""
import json
from pathlib import Path
import re
from pypdf import PdfReader

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [('aryan-ai.pdf', 'AI and agents resume', 'ai'), ('aryan-ai-research.pdf', 'AI research resume', 'research'), ('aryan-systems.pdf', 'Software engineering resume', 'systems'), ('aryan-robotics.pdf', 'Robotics resume', 'robotics')]
chunks = []
seen = set()
for filename, title, source in SOURCES:
    text = ' '.join(' '.join(page.extract_text().split()) for page in PdfReader(ROOT / 'public/resumes' / filename).pages)
    # Older resume education and contact headers are superseded by the latest profile.
    # They are intentionally excluded rather than allowed to contradict the new GPA.
    start = text.find('TECHNICAL SKILLS')
    if start < 0:
        raise ValueError(f'Missing expected section in {filename}')
    text = text[start:]
    sections = re.split(r'\b(TECHNICAL SKILLS|EXPERIENCE|PROJECTS|ACHIEVEMENTS)\b', text)
    for i in range(1, len(sections), 2):
        heading, content = sections[i], sections[i+1]
        words = content.split()
        section = {'TECHNICAL SKILLS':'skills', 'EXPERIENCE':'experience', 'PROJECTS':'projects', 'ACHIEVEMENTS':'about'}[heading]
        for n, offset in enumerate(range(0, len(words), 100)):
            part = ' '.join(words[offset:offset+125])
            if not part or part in seen:
                continue
            seen.add(part)
            chunks.append({'id':f'resume-{source}-{section}-{n}', 'title':f'{title} · {heading.title()} {n+1}', 'section':section, 'source':source, 'text':part, 'archival':True})
(ROOT / 'src/resume-corpus.js').write_text('// Generated by scripts/ingest_resumes.py. Newer curated profile facts take precedence.\nexport const resumeCorpus = '+json.dumps(chunks, ensure_ascii=False, indent=2)+';\n')
print(f'Indexed {len(chunks)} passages from all four resumes.')
